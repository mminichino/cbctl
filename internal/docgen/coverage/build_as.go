package coverage

import (
	"fmt"
	"sort"
	"strings"

	"github.com/mminichino/cbctl/internal/docgen/data"
)

// BuildAppServices renders docs/backlog/release-2.0.0/API-COVERAGE-APP-SERVICES.md.
func BuildAppServices(snap Snapshot, bundle data.Bundle, table []string) string {
	type row struct {
		tag, method, path, summary, command, note string
	}
	var ops []row
	seen := map[string]bool{}
	for _, o := range snap.Operations {
		if !isAppServices(o.Tag, o.Path) {
			continue
		}
		key := o.Method + " " + o.Path
		spec, ok := bundle.ASOps[key]
		if !ok {
			return fmt.Sprintf("# ERROR: unmapped App Services operation %s\n", key)
		}
		seen[key] = true
		ops = append(ops, row{o.Tag, o.Method, o.Path, o.Summary, spec.Command, spec.Note})
	}
	for key := range bundle.ASOps {
		if !seen[key] {
			return fmt.Sprintf("# ERROR: AS_OPS maps operations not in snapshot: %s\n", key)
		}
	}
	by := map[string][]row{}
	for _, r := range ops {
		by[r.tag] = append(by[r.tag], r)
	}
	areaTags := map[string]bool{}
	for _, a := range bundle.ASAreas {
		areaTags[a.Tag] = true
	}
	if len(by) != len(areaTags) {
		var diff []string
		for t := range by {
			if !areaTags[t] {
				diff = append(diff, t)
			}
		}
		for t := range areaTags {
			if _, ok := by[t]; !ok {
				diff = append(diff, t)
			}
		}
		sort.Strings(diff)
		return fmt.Sprintf("# ERROR: App Services tags changed: %v\n", diff)
	}

	// Preserve AS_OPS encounter order for commands.
	cmds := map[string][]string{}
	var cmdOrder []string
	for _, r := range ops {
		if _, ok := cmds[r.command]; !ok {
			cmdOrder = append(cmdOrder, r.command)
		}
		cmds[r.command] = append(cmds[r.command], r.method+" "+short(r.path))
	}

	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }
	w("# Management API coverage — App Services (release 2.0.0)\n")
	w(fmt.Sprintf("> Generated by `cbdev docs coverage` from the Capella Management API %s spec "+
		"([source](%s), snapshot of %s). Every App Services operation in the spec "+
		"appears exactly once. Operational-database coverage is in "+
		"[release-1.0.0/API-COVERAGE.md](../release-1.0.0/API-COVERAGE.md) and "+
		"[release-1.5.0/API-COVERAGE.md](../release-1.5.0/API-COVERAGE.md). Don't edit by hand.\n",
		snap.APIVersion, snap.Source, snap.Retrieved))
	w("## Scope\n")
	w(fmt.Sprintf("The spec has **%d operations**. This document tracks the **%d App Services and App Endpoints "+
		"operations**, including the 4 free-tier App Service operations that the spec tags *Free Tier*. Releases 1.0.0 "+
		"and 1.5.0 cover the operational database. The AI operations are not planned for now.\n",
		len(snap.Operations), len(ops)))
	for _, line := range table {
		w(line)
	}
	w("No stories are written for 2.0.0 yet. Every row is ⏭️ **Not started**, and every command name is a proposal " +
		"that follows the 1.0.0 conventions: noun-verb, declarative through `plan`/`apply`, and idempotent.\n")
	w("## Summary\n")
	w("| | Count | ✅ Done | 🟡 Partial | ⬜ Not built | ⏭️ Not started | Coverage |")
	w("|---|---|---|---|---|---|---|")
	w(fmt.Sprintf("| **API operations** | **%d** | 0 | 0 | 0 | %d | 0%% |", len(ops), len(ops)))
	w(fmt.Sprintf("| **Proposed commands** | **%d** | 0 | 0 | 0 | %d | 0%% |", len(cmds), len(cmds)))
	w("")
	w("### By area\n")
	w("| Area | Operations | Proposed commands |")
	w("|---|---|---|")
	for _, a := range bundle.ASAreas {
		rows := by[a.Tag]
		cmdSet := map[string]bool{}
		for _, r := range rows {
			cmdSet[r.command] = true
		}
		w(fmt.Sprintf("| [%s](%s) | %d | %d |", a.Label, anchor(a.Tag), len(rows), len(cmdSet)))
	}
	w(fmt.Sprintf("| **Total** | **%d** | **%d** |", len(ops), len(cmds)))
	w("")
	w("*A command can serve more than one operation, for example `app-service create` with and without " +
		"`--free-tier`, so the per-area command counts add up to more than the distinct total.*\n")
	w("## Dependencies on 1.0.0\n")
	w("- An App Service is created **under a provisioned cluster** (`POST …/clusters/{c}/appservices`), so it builds on " +
		"the 1.0.0 cluster, bucket, scope and collection reconcilers. App Endpoints bind to a bucket's scopes and " +
		"collections, which needs [CAP-025](../CAP-ID-MAP.md#cap-025).")
	w("- `POST …/clusters/{c}/activationState` (1.0.0 `cluster power on`, " +
		"[CAP-019](../CAP-ID-MAP.md#cap-019)) already accepts `turnOnLinkedAppService`. In 1.0.0 it " +
		"is always `false`; 2.0.0 should expose it.")
	w("- Deleting a cluster that has a linked App Service needs an ordering rule in the 1.0.0 dependency graph " +
		"([00-architecture.md](../release-1.0.0/00-architecture.md) §4.2): delete the App Service first.")
	w("- The patterns for allowed CIDRs, audit-log export, private endpoints and power on/off mirror the " +
		"cluster-level 1.0.0 work, so their reconcilers and tests can be reused.\n")
	w("## Command dictionary (proposed)\n")
	w("| Command | Status | API operations |")
	w("|---|---|---|")
	for _, c := range cmdOrder {
		lst := cmds[c]
		w(fmt.Sprintf("| `cbctl capella %s` | ⏭️ Not started | %s |", c,
			strings.Join(mapFmt(lst, func(x string) string { return "`" + x + "`" }), "<br>")))
	}
	w("")
	w("## Operation-by-operation table\n")
	w("Paths are abbreviated: `{org}` = `/v4/organizations/{organizationId}`, `{p}` = projectId, `{c}` = clusterId, " +
		"`{a}` = appServiceId, `{e}` = appEndpointName.\n")
	for _, a := range bundle.ASAreas {
		rows := by[a.Tag]
		w(fmt.Sprintf("### %s — %d ops\n", a.Label, len(rows)))
		w(fmt.Sprintf("[API reference](%s)\n", anchor(a.Tag)))
		w("| Operation | Method | Path | Proposed command | Status | Notes |")
		w("|---|---|---|---|---|---|")
		for _, r := range rows {
			w(fmt.Sprintf("| %s | `%s` | `%s` | `%s` | ⏭️ Not started | %s |",
				r.summary, r.method, short(r.path), r.command, r.note))
		}
		w("")
	}
	return b.String()
}
