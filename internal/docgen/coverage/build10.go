package coverage

import (
	"fmt"
	"sort"
	"strings"

	"github.com/mminichino/cbctl/internal/docgen/data"
)

// Build1_0 renders docs/backlog/release-1.0.0/API-COVERAGE.md.
func Build1_0(snap Snapshot, known Known, bundle data.Bundle, table []string, ops []collectedOp, excl map[string]int) string {
	for i := range ops {
		ops[i].Status = opStatus(ops[i], known, Rel10)
	}
	cmdStatus := map[string]string{}
	for n, c := range bundle.Commands {
		cmdStatus[n] = statusOf(c.Stories, known, Rel10)
	}
	cmdOps := map[string][]string{}
	for _, o := range ops {
		for _, n := range o.Names {
			cmdOps[n] = append(cmdOps[n], o.Method+" "+short(o.Path))
		}
	}
	count := func(rows []collectedOp) []int {
		c := map[string]int{}
		for _, r := range rows {
			c[r.Status]++
		}
		out := make([]int, len(order))
		for i, s := range order {
			out[i] = c[s]
		}
		return out
	}
	var ops10 []collectedOp
	for _, o := range ops {
		if o.Status != Later {
			ops10 = append(ops10, o)
		}
	}
	cmds10 := map[string]string{}
	// Preserve insertion order from commands.json by sorting keys for stable output of "all",
	// but for cmds10 keep deterministic sorted order matching Python 3.7+ dict insertion…
	// Python iterates COMMANDS in insertion order. Our JSON object order is preserved by encoding/json
	// only if we re-read; Go map iteration is random. Use sorted keys for stability (pragmatic).
	cmdNames := sortedKeys(bundle.Commands)
	for _, n := range cmdNames {
		if cmdStatus[n] != Later {
			cmds10[n] = cmdStatus[n]
		}
	}
	cmds10Names := make([]string, 0, len(cmds10))
	for _, n := range cmdNames {
		if _, ok := cmds10[n]; ok {
			cmds10Names = append(cmds10Names, n)
		}
	}
	oc, o10 := count(ops), count(ops10)
	cc := map[string]int{}
	for _, s := range cmdStatus {
		cc[s]++
	}
	c10 := map[string]int{}
	for _, s := range cmds10 {
		c10[s]++
	}
	type wfRow struct {
		name, status, stories, note string
	}
	var wf []wfRow
	wc := map[string]int{}
	for _, w := range bundle.Workflow {
		st := statusOf(w.Stories, known, Rel10)
		wf = append(wf, wfRow{w.Name, st, strings.Join(w.Stories, ", "), w.Note})
		wc[st]++
	}
	by := map[string][]collectedOp{}
	for _, o := range ops {
		by[o.Tag] = append(by[o.Tag], o)
	}

	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }
	w("# Management API coverage — operational database\n")
	w(fmt.Sprintf("> Generated by `cbdev docs coverage` from the Capella Management API %s spec "+
		"([source](%s), snapshot of %s in "+
		"[docs/api](../api/management-api-v4.0-operations.json)), the command dictionary in `internal/docgen/data` and the "+
		"**Status** of each story. Every in-scope operation in the spec appears exactly once. Don't edit by hand: "+
		"change a story's status and run `make docs`. CI fails when this file is stale. Story progress: "+
		"[README.md](README.md).\n", snap.APIVersion, snap.Source, snap.Retrieved))
	w("## Scope\n")
	w(fmt.Sprintf("The spec has **%d operations**. Release 1.0.0 is about the operational database, so this report "+
		"covers the **%d operational-database operations**. Two groups are left out:\n", len(snap.Operations), len(ops)))
	w(fmt.Sprintf("- **%d App Services / App Endpoints operations**, including the 4 free-tier App Service operations. "+
		"They are tracked in [release 2.0.0: App Services API coverage](../release-2.0.0/API-COVERAGE-APP-SERVICES.md).", excl["as"]))
	w(fmt.Sprintf("- **%d AI operations** (AI Data Plane, AI Workflows, Models, AI Agent Memory, MCP servers and tools). Not planned for now.\n", excl["ai"]))
	for _, line := range table {
		w(line)
	}
	w("**Status legend**\n")
	w("| Status | Meaning |\n|---|---|")
	w(fmt.Sprintf("| %s | cbctl calls this operation, from a command, from `plan`/`apply`, or internally, and every story "+
		"it depends on is Implemented. |", Done))
	w(fmt.Sprintf("| %s | Some of it is built (some of its stories are Implemented, or a read during `import`); the row says "+
		"what is left. |", Part))
	w(fmt.Sprintf("| %s | Planned for 1.0.0 in a story that is not Implemented yet. Its command may exist as a stub that "+
		"prints \"not available in this build\". |", Todo))
	w(fmt.Sprintf("| %s | Not needed: another operation already provides the same data. |", None))
	w(fmt.Sprintf("| %s | Outside the 1.0.0 scope (see [00-architecture.md §14](00-architecture.md)). Planned for "+
		"[release 1.5.0](../release-1.5.0/API-COVERAGE.md), which tracks their stories. |", Later))
	w("")
	w("## Summary\n")
	w("### API operations\n")
	w("| | Operations | ✅ Done | 🟡 Partial | ⬜ Not built | ➖ Not needed | ⏭️ Not in 1.0 | Coverage (done / total) |")
	w("|---|---|---|---|---|---|---|---|")
	w(fmt.Sprintf("| **Planned for 1.0.0** | **%d** | %d | %d | %d | %d | — | **%s** (done / needed) |",
		len(ops10), o10[0], o10[1], o10[2], o10[3], pct(o10[0], len(ops10)-o10[3])))
	w(fmt.Sprintf("| All operational-database operations | %d | %d | %d | %d | %d | %d | %s |",
		len(ops), oc[0], oc[1], oc[2], oc[3], oc[4], pct(oc[0], len(ops))))
	w("")
	w("### Commands\n")
	w("| | Commands | ✅ Done | 🟡 Partial | ⬜ Not built (stub) | ⏭️ Not in 1.0 | Coverage (done / total) |")
	w("|---|---|---|---|---|---|---|")
	w(fmt.Sprintf("| **Resource commands planned for 1.0.0** | **%d** | %d | %d | %d | — | **%s** |",
		len(cmds10), c10[Done], c10[Part], c10[Todo], pct(c10[Done], len(cmds10))))
	w(fmt.Sprintf("| Workflow commands (`plan`, `apply`, …) | %d | %d | %d | %d | — | %s |",
		len(wf), wc[Done], wc[Part], wc[Todo], pct(wc[Done], len(wf))))
	w(fmt.Sprintf("| All resource commands, including later releases | %d | %d | %d | %d | %d | %s |",
		len(bundle.Commands), cc[Done], cc[Part], cc[Todo], cc[Later], pct(cc[Done], len(bundle.Commands))))
	w("")
	w("*Each verb counts as one command (for example `cluster schedule pause`). Each command maps to one or more API " +
		"operations. For example, `bucket create` calls both the provisioned and the free-tier create.*\n")
	w("### By area\n")
	w("| Area | 1.0.0 scope | Ops | ✅ | 🟡 | ⬜ | ➖ | ⏭️ |")
	w("|---|---|---|---|---|---|---|---|")
	for _, a := range bundle.Areas {
		c := count(by[a.Tag])
		cells := make([]string, len(c))
		for i, x := range c {
			if x == 0 {
				cells[i] = ""
			} else {
				cells[i] = fmt.Sprintf("%d", x)
			}
		}
		scoped := "No"
		if a.In10 {
			scoped = "Yes"
		}
		w(fmt.Sprintf("| [%s](%s) | %s | %d | %s |", a.Label, anchor(a.Tag), scoped, len(by[a.Tag]), strings.Join(cells, " | ")))
	}
	w(fmt.Sprintf("| **Total** | | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** |",
		len(ops), oc[0], oc[1], oc[2], oc[3], oc[4]))
	w("")

	w("## What is left for 1.0.0\n")
	var left []collectedOp
	for _, o := range ops10 {
		if o.Status == Part || o.Status == Todo {
			left = append(left, o)
		}
	}
	type leftEntry struct{ ops, cmds []string }
	perStory := map[string]*leftEntry{}
	var storyOrder []string
	// Sort left by open stories key for stability
	sort.SliceStable(left, func(i, j int) bool {
		return strings.Join(openStories(left[i].Stories, known, Rel10), ",") <
			strings.Join(openStories(left[j].Stories, known, Rel10), ",")
	})
	for _, o := range left {
		for _, s := range openStories(o.Stories, known, Rel10) {
			e, ok := perStory[s]
			if !ok {
				e = &leftEntry{}
				perStory[s] = e
				storyOrder = append(storyOrder, s)
			}
			e.ops = append(e.ops, fmt.Sprintf("`%s %s`", o.Method, short(o.Path)))
			for _, n := range o.Names {
				inCmd := false
				for _, cs := range bundle.Commands[n].Stories {
					if cs == s {
						inCmd = true
						break
					}
				}
				inReq := false
				for _, r := range o.Requires {
					if r == s {
						inReq = true
						break
					}
				}
				if inCmd || inReq {
					e.cmds = append(e.cmds, "`"+n+"`")
				}
			}
		}
	}
	for _, row := range wf {
		if row.status == Done {
			continue
		}
		sts := strings.Split(row.stories, ", ")
		for _, s := range openStories(sts, known, Rel10) {
			e, ok := perStory[s]
			if !ok {
				e = &leftEntry{}
				perStory[s] = e
				storyOrder = append(storyOrder, s)
			}
			e.cmds = append(e.cmds, "`"+row.name+"`")
		}
	}
	sort.Slice(storyOrder, func(i, j int) bool {
		a, b := storyOrder[i], storyOrder[j]
		if a == NoStory {
			return false
		}
		if b == NoStory {
			return true
		}
		return a < b
	})
	// unique storyOrder
	seenS := map[string]bool{}
	var uniqOrder []string
	for _, s := range storyOrder {
		if !seenS[s] {
			seenS[s] = true
			uniqOrder = append(uniqOrder, s)
		}
	}
	sort.Slice(uniqOrder, func(i, j int) bool {
		a, b := uniqOrder[i], uniqOrder[j]
		if a == NoStory != (b == NoStory) {
			return a != NoStory
		}
		return a < b
	})
	w(fmt.Sprintf("%d operations are partial or not built, across %d stories:\n", len(left), len(perStory)))
	w("| Story | Status | Operations | Commands |")
	w("|---|---|---|---|")
	for _, s := range uniqOrder {
		e := perStory[s]
		story := "**No story yet** (gap)"
		status := "—"
		if s != NoStory {
			story = fmt.Sprintf("[%s](%s) %s", s, storyLink(s, known, Rel10), known[s].Title)
			status = known[s].Status
		}
		opsTxt := strings.Join(uniq(e.ops), ", ")
		if opsTxt == "" {
			opsTxt = "— (uses the operations above)"
		}
		w(fmt.Sprintf("| %s | %s | %s | %s |", story, status, opsTxt, strings.Join(uniq(e.cmds), ", ")))
	}
	w("")
	w("### Gaps found\n")
	for i, g := range bundle.Gaps {
		w(fmt.Sprintf("%d. %s", i+1, g))
	}
	w("")

	w("## Command dictionary\n")
	w("Every resource command: built, stubbed, or planned for a later release, with the API operations it calls. A " +
		"command's status comes from its stories.\n")
	w("### Planned for 1.0.0\n")
	w("| Command | Status | Stories | API operations | What's left |")
	w("|---|---|---|---|---|")
	for _, n := range cmds10Names {
		st := cmds10[n]
		c := bundle.Commands[n]
		opsTxt := strings.Join(mapFmt(uniq(cmdOps[n]), func(x string) string { return "`" + x + "`" }), "<br>")
		left := ""
		if st != Done {
			left = c.Left
		}
		w(fmt.Sprintf("| `cbctl capella %s` | %s | %s | %s | %s |", n, st, strings.Join(c.Stories, ", "), opsTxt, left))
	}
	w("")
	w("### Workflow commands (not one-to-one with an API operation)\n")
	w("| Command | Status | Stories | Notes |")
	w("|---|---|---|---|")
	for _, row := range wf {
		w(fmt.Sprintf("| `cbctl capella %s` | %s | %s | %s |", row.name, row.status, row.stories, row.note))
	}
	w("")
	w("### Commands outside 1.0.0\n")
	w(fmt.Sprintf("<details><summary>%d commands planned for a later release</summary>\n", cc[Later]))
	w("| Command | Release | Stories | API operations |")
	w("|---|---|---|---|")
	for _, n := range cmdNames {
		if cmdStatus[n] != Later {
			continue
		}
		sts := bundle.Commands[n].Stories
		var links []string
		for _, s := range sts {
			if s != NoStory {
				links = append(links, fmt.Sprintf("[%s](%s)", s, storyLink(s, known, Rel10)))
			}
		}
		linkTxt := "—"
		if len(links) > 0 {
			linkTxt = strings.Join(links, ", ")
		}
		rel := releaseOf(sts, known)
		if rel == "" {
			rel = "—"
		}
		opsTxt := strings.Join(mapFmt(uniq(cmdOps[n]), func(x string) string { return "`" + x + "`" }), "<br>")
		w(fmt.Sprintf("| `cbctl capella %s` | %s | %s | %s |", n, rel, linkTxt, opsTxt))
	}
	w("\n</details>\n")

	w("## Operation-by-operation table\n")
	w("Paths are abbreviated: `{org}` = `/v4/organizations/{organizationId}`, `{p}` = projectId, `{c}` = clusterId, " +
		"`{b}` = bucketId.\n")
	for _, a := range bundle.Areas {
		rows := by[a.Tag]
		c := count(rows)
		var parts []string
		for i, s := range order {
			if c[i] > 0 {
				parts = append(parts, fmt.Sprintf("%d %s", c[i], strings.SplitN(s, " ", 2)[0]))
			}
		}
		w(fmt.Sprintf("### %s — %d ops (%s)\n", a.Label, len(rows), strings.Join(parts, ", ")))
		extra := ""
		if !a.In10 {
			extra = " · out of 1.0.0 scope"
		}
		w(fmt.Sprintf("[API reference](%s)%s\n", anchor(a.Tag), extra))
		w("| Operation | Method | Path | cbctl command | Status | Notes / what's left |")
		w("|---|---|---|---|---|---|")
		for _, o := range rows {
			cmdtxt := o.Commands
			if len(o.Names) > 0 {
				cmdtxt = strings.Join(mapFmt(o.Names, func(x string) string { return "`" + x + "`" }), " / ")
			}
			notes := strings.TrimSpace(o.Note)
			if o.Status != Done && o.Left != "" {
				if notes != "" {
					notes += " "
				}
				notes += o.Left
			}
			w(fmt.Sprintf("| %s | `%s` | `%s` | %s | %s | %s |", o.Summary, o.Method, short(o.Path), cmdtxt, o.Status, notes))
		}
		w("")
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	// Prefer JSON file order: read isn't available; use lexical for stability of --check.
	// Actually for command dictionary matching Python insertion order matters for human diffs.
	// We'll preserve by re-decoding with ordered approach in data package later if needed.
	sort.Strings(keys)
	return keys
}

func uniq(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, x := range in {
		if !seen[x] {
			seen[x] = true
			out = append(out, x)
		}
	}
	return out
}

func mapFmt(in []string, f func(string) string) []string {
	out := make([]string, len(in))
	for i, x := range in {
		out[i] = f(x)
	}
	return out
}
