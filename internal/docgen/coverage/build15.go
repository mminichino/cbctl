package coverage

import (
	"fmt"
	"sort"
	"strings"

	"github.com/mminichino/cbctl/internal/docgen/data"
)

// Build1_5 renders docs/backlog/release-1.5.0/API-COVERAGE.md.
func Build1_5(snap Snapshot, known Known, bundle data.Bundle, table []string, ops []collectedOp, excl map[string]int) string {
	// ops already have Rel15 status set by Generate.
	planned15 := func(sts []string) bool { return releaseOf(sts, known) == Rel15 }

	var ops15, earlier []collectedOp
	for _, o := range ops {
		if planned15(o.Stories) {
			ops15 = append(ops15, o)
		} else {
			earlier = append(earlier, o)
		}
	}
	cmds15 := map[string]string{}
	cmdNames := sortedKeys(bundle.Commands)
	var cmds15Names []string
	for _, n := range cmdNames {
		c := bundle.Commands[n]
		if planned15(c.Stories) {
			cmds15[n] = statusOf(c.Stories, known, Rel15)
			cmds15Names = append(cmds15Names, n)
		}
	}
	cmdOps := map[string][]string{}
	for _, o := range ops15 {
		for _, n := range o.Names {
			cmdOps[n] = append(cmdOps[n], o.Method+" "+short(o.Path))
		}
	}
	order15 := []string{Done, Part, Todo}
	count := func(rows []collectedOp) []int {
		c := map[string]int{}
		for _, r := range rows {
			c[r.Status]++
		}
		out := make([]int, len(order15))
		for i, s := range order15 {
			out[i] = c[s]
		}
		return out
	}
	c15 := count(ops15)
	cc := map[string]int{}
	for _, s := range cmds15 {
		cc[s]++
	}
	doneBefore := 0
	notNeeded := 0
	for _, o := range earlier {
		if o.Status == Done {
			doneBefore++
		}
	}
	for _, o := range ops {
		if o.Status == None {
			notNeeded++
		}
	}
	by := map[string][]collectedOp{}
	for _, o := range ops15 {
		by[o.Tag] = append(by[o.Tag], o)
	}
	beforeBy := map[string]int{}
	for _, o := range earlier {
		beforeBy[o.Tag]++
	}

	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }
	w("# Management API coverage — release 1.5.0\n")
	w(fmt.Sprintf("> Generated by `cbdev docs coverage` from the Capella Management API %s spec "+
		"([source](%s), snapshot of %s in "+
		"[docs/api](../api/management-api-v4.0-operations.json)), the command dictionary in `internal/docgen/data` and the "+
		"**Status** of each story. Don't edit by hand: change a story's status and run `make docs`. CI fails when "+
		"this file is stale. Story progress: [README.md](README.md).\n", snap.APIVersion, snap.Source, snap.Retrieved))
	w("## Scope\n")
	w(fmt.Sprintf("The spec has **%d operations**, of which **%d are operational-database "+
		"operations**. [Release 1.0.0](../release-1.0.0/API-COVERAGE.md) covers %d of them. **Release 1.5.0 "+
		"plans the other %d**, so that after 1.5.0 cbctl calls every operational-database operation it "+
		"needs. Two groups stay out:\n", len(snap.Operations), len(ops), len(earlier), len(ops15)))
	w(fmt.Sprintf("- **%d App Services / App Endpoints operations**: release 2.0.0 "+
		"([API coverage](../release-2.0.0/API-COVERAGE-APP-SERVICES.md)).", excl["as"]))
	w(fmt.Sprintf("- **%d AI operations** (AI Data Plane, AI Workflows, Models, AI Agent Memory, MCP servers and tools). "+
		"Not planned for now.\n", excl["ai"]))
	for _, line := range table {
		w(line)
	}
	w("**Status legend**\n")
	w("| Status | Meaning |\n|---|---|")
	w(fmt.Sprintf("| %s | cbctl calls this operation and every story it depends on is Implemented. |", Done))
	w(fmt.Sprintf("| %s | Some of its stories are Implemented; the row says what is left. |", Part))
	w(fmt.Sprintf("| %s | Planned for 1.5.0 in a story that is not Implemented yet. |", Todo))
	w("")
	w("## Summary\n")
	w("| | Count | ✅ Done | 🟡 Partial | ⬜ Not built | Coverage (done / total) |")
	w("|---|---|---|---|---|---|")
	w(fmt.Sprintf("| **API operations planned for 1.5.0** | **%d** | %d | %d | %d | **%s** |",
		len(ops15), c15[0], c15[1], c15[2], pct(c15[0], len(ops15))))
	w(fmt.Sprintf("| **Resource commands planned for 1.5.0** | **%d** | %d | %d | %d | **%s** |",
		len(cmds15), cc[Done], cc[Part], cc[Todo], pct(cc[Done], len(cmds15))))
	remaining := len(earlier) - notNeeded - doneBefore
	w(fmt.Sprintf("| Operational database after 1.5.0 (1.0.0 + 1.5.0) | %d | %d | %d | %d | %s |",
		len(ops)-notNeeded, doneBefore+c15[0], c15[1], c15[2]+remaining,
		pct(doneBefore+c15[0], len(ops)-notNeeded)))
	w("")
	plural := "s"
	if notNeeded == 1 {
		plural = ""
	}
	w(fmt.Sprintf("*The last row leaves out the %d operation%s marked ➖ Not needed in the "+
		"1.0.0 report. Each verb counts as one command; a command can call more than one operation.*\n", notNeeded, plural))
	w("### By area\n")
	w("| Area | In 1.0.0 | 1.5.0 ops | ✅ | 🟡 | ⬜ | Stories |")
	w("|---|---|---|---|---|---|---|")
	for _, a := range bundle.Areas {
		rows := by[a.Tag]
		if len(rows) == 0 {
			continue
		}
		c := count(rows)
		cells := make([]string, len(c))
		for i, x := range c {
			if x == 0 {
				cells[i] = ""
			} else {
				cells[i] = fmt.Sprintf("%d", x)
			}
		}
		storySet := map[string]bool{}
		for _, o := range rows {
			for _, s := range o.Stories {
				if s != NoStory && known[s].Release == Rel15 {
					storySet[s] = true
				}
			}
		}
		var storyList []string
		for s := range storySet {
			storyList = append(storyList, s)
		}
		sort.Strings(storyList)
		var links []string
		for _, s := range storyList {
			links = append(links, fmt.Sprintf("[%s](%s)", s, storyLink(s, known, Rel15)))
		}
		in10 := ""
		if beforeBy[a.Tag] > 0 {
			in10 = fmt.Sprintf("%d", beforeBy[a.Tag])
		}
		w(fmt.Sprintf("| [%s](%s) | %s | %d | %s | %s |",
			a.Label, anchor(a.Tag), in10, len(rows), strings.Join(cells, " | "), strings.Join(links, ", ")))
	}
	w(fmt.Sprintf("| **Total** | | **%d** | **%d** | **%d** | **%d** | |", len(ops15), c15[0], c15[1], c15[2]))
	w("")

	w("## What is left for 1.5.0\n")
	var left []collectedOp
	for _, o := range ops15 {
		if o.Status == Part || o.Status == Todo {
			left = append(left, o)
		}
	}
	type leftEntry struct{ ops, cmds []string }
	perStory := map[string]*leftEntry{}
	var storyOrder []string
	for _, o := range left {
		for _, s := range openStories(o.Stories, known, Rel15) {
			e, ok := perStory[s]
			if !ok {
				e = &leftEntry{}
				perStory[s] = e
				storyOrder = append(storyOrder, s)
			}
			e.ops = append(e.ops, fmt.Sprintf("`%s %s`", o.Method, short(o.Path)))
			for _, n := range o.Names {
				inCmd := false
				for _, cs := range bundle.Commands[n].Stories {
					if cs == s {
						inCmd = true
						break
					}
				}
				inReq := false
				for _, r := range o.Requires {
					if r == s {
						inReq = true
						break
					}
				}
				if inCmd || inReq {
					e.cmds = append(e.cmds, "`"+n+"`")
				}
			}
		}
	}
	sort.Slice(storyOrder, func(i, j int) bool {
		a, b := storyOrder[i], storyOrder[j]
		if (a == NoStory) != (b == NoStory) {
			return a != NoStory
		}
		return a < b
	})
	seen := map[string]bool{}
	var uniqOrder []string
	for _, s := range storyOrder {
		if !seen[s] {
			seen[s] = true
			uniqOrder = append(uniqOrder, s)
		}
	}
	w(fmt.Sprintf("%d operations are partial or not built, across %d stories:\n", len(left), len(perStory)))
	w("| Story | Status | Operations | Commands |")
	w("|---|---|---|---|")
	for _, s := range uniqOrder {
		e := perStory[s]
		story := "**No story yet** (gap)"
		status := "—"
		if s != NoStory {
			story = fmt.Sprintf("[%s](%s) %s", s, storyLink(s, known, Rel15), known[s].Title)
			status = known[s].Status
		}
		w(fmt.Sprintf("| %s | %s | %s | %s |", story, status, strings.Join(uniq(e.ops), ", "), strings.Join(uniq(e.cmds), ", ")))
	}
	w("")

	w("## Command dictionary\n")
	w("Every resource command planned for 1.5.0, with the API operations it calls. A command's status comes from its " +
		"stories. Workflow commands (`plan`, `apply`, `sync`, `drift`, `destroy`) gain the new resources through the " +
		"stories' acceptance criteria.\n")
	w("| Command | Status | Stories | API operations | What's left |")
	w("|---|---|---|---|---|")
	for _, n := range cmds15Names {
		st := cmds15[n]
		c := bundle.Commands[n]
		var links []string
		for _, s := range c.Stories {
			if s != NoStory {
				links = append(links, fmt.Sprintf("[%s](%s)", s, storyLink(s, known, Rel15)))
			}
		}
		opsTxt := strings.Join(mapFmt(uniq(cmdOps[n]), func(x string) string { return "`" + x + "`" }), "<br>")
		leftTxt := ""
		if st != Done {
			leftTxt = c.Left
		}
		w(fmt.Sprintf("| `cbctl capella %s` | %s | %s | %s | %s |", n, st, strings.Join(links, ", "), opsTxt, leftTxt))
	}
	w("")

	w("## Operation-by-operation table\n")
	w("Paths are abbreviated: `{org}` = `/v4/organizations/{organizationId}`, `{p}` = projectId, `{c}` = clusterId, " +
		"`{b}` = bucketId.\n")
	for _, a := range bundle.Areas {
		rows := by[a.Tag]
		if len(rows) == 0 {
			continue
		}
		c := count(rows)
		var parts []string
		for i, s := range order15 {
			if c[i] > 0 {
				parts = append(parts, fmt.Sprintf("%d %s", c[i], strings.SplitN(s, " ", 2)[0]))
			}
		}
		w(fmt.Sprintf("### %s — %d ops (%s)\n", a.Label, len(rows), strings.Join(parts, ", ")))
		extra := ""
		if beforeBy[a.Tag] > 0 {
			extra = fmt.Sprintf(" · %d more in [1.0.0](../release-1.0.0/API-COVERAGE.md)", beforeBy[a.Tag])
		}
		w(fmt.Sprintf("[API reference](%s)%s\n", anchor(a.Tag), extra))
		w("| Operation | Method | Path | cbctl command | Status | Notes / what's left |")
		w("|---|---|---|---|---|---|")
		for _, o := range rows {
			cmdtxt := o.Commands
			if len(o.Names) > 0 {
				cmdtxt = strings.Join(mapFmt(o.Names, func(x string) string { return "`" + x + "`" }), " / ")
			}
			notes := strings.TrimSpace(o.Note)
			if o.Status != Done && o.Left != "" {
				if notes != "" {
					notes += " "
				}
				notes += o.Left
			}
			w(fmt.Sprintf("| %s | `%s` | `%s` | %s | %s | %s |", o.Summary, o.Method, short(o.Path), cmdtxt, o.Status, notes))
		}
		w("")
	}
	return b.String()
}
