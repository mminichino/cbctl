// CompareOptions configures the §9.7 parity oracle.
type CompareOptions struct {
	BacklogRoot   string   // cbctl docs/backlog
	CapellaDocs   string   // <capellactl>/docs
	InProgressIDs []string // default CAP-032, CAP-055
	AllowDiff     bool     // report diffs but treat as soft success
}

// CompareResult summarizes regenerated vs rewritten-capellactl report diffs.
type CompareResult struct {
	Reports []ReportDiff
}

// ReportDiff is one coverage report comparison.
type ReportDiff struct {
	Name       string
	Differs    bool
	OursLines  int
	TheirLines int
	Sample     string // first differing region
}

// CompareWith regenerates the three API coverage reports with stories.yaml statuses
// forced to capellactl's real statuses (all Implemented except InProgressIDs) and
// diffs them against capellactl's committed reports after applying §9.5 rewrite rules.
//
// Full byte identity is not yet guaranteed (Go table order / banner differ from Python);
// this implements the oracle plumbing required by §9.7.
func CompareWith(opts CompareOptions) (CompareResult, error) {
	var res CompareResult
	if opts.BacklogRoot == "" || opts.CapellaDocs == "" {
		return res, fmt.Errorf("coverage compare: backlog root and --compare-with dir are required")
	}
	inProgress := opts.InProgressIDs
	if len(inProgress) == 0 {
		inProgress = []string{"CAP-032", "CAP-055"}
	}
	inProg := map[string]bool{}
	for _, id := range inProgress {
		inProg[id] = true
	}

	bundle, err := data.Load()
	if err != nil {
		return res, err
	}
	snap, err := LoadSnapshot(filepath.Join(opts.BacklogRoot, "api", "management-api-v4.0-operations.json"))
	if err != nil {
		return res, err
	}
	known, err := stories.LoadAll(opts.BacklogRoot)
	if err != nil {
		return res, err
	}
	// Force only release-1.0.0 rows (stories.yaml). 1.5.0/2.0.0 keep file statuses
	// (Not started) so the oracle matches capellactl's committed reports.
	for id, s := range known {
		if s.Release != Rel10 {
			continue
		}
		if s.Status == "Descoped" {
			continue
		}
		if inProg[id] {
			s.Status = "In progress"
		} else {
			s.Status = "Implemented"
		}
		known[id] = s
	}

	table, ops, excl, err := breakdown(snap, known, bundle)
	if err != nil {
		return res, err
	}
	ops10 := append([]collectedOp(nil), ops...)
	ops15 := append([]collectedOp(nil), ops...)
	for i := range ops15 {
		ops15[i].Status = opStatus(ops15[i], known, Rel15)
	}
	ours := map[string]string{
		"release-1.0.0/API-COVERAGE.md":              Build1_0(snap, known, bundle, table, ops10, excl),
		"release-1.5.0/API-COVERAGE.md":              Build1_5(snap, known, bundle, table, ops15, excl),
		"release-2.0.0/API-COVERAGE-APP-SERVICES.md": BuildAppServices(snap, bundle, table),
	}

	pairs := []struct {
		name, capellaRel string
	}{
		{"release-1.0.0/API-COVERAGE.md", "release-1.0.0/API-COVERAGE.md"},
		{"release-1.5.0/API-COVERAGE.md", "release-1.5.0/API-COVERAGE.md"},
		{"release-2.0.0/API-COVERAGE-APP-SERVICES.md", "release-2.0.0/API-COVERAGE-APP-SERVICES.md"},
	}
	for _, p := range pairs {
		theirsRaw, err := os.ReadFile(filepath.Join(opts.CapellaDocs, p.capellaRel))
		if err != nil {
			return res, fmt.Errorf("read capellactl %s: %w", p.capellaRel, err)
		}
		rewritten, _ := port.Rewrite(string(theirsRaw), port.RewriteOpts{Profile: "guide"})
		oursNorm := stripCoverageBanner(ours[p.name])
		theirsNorm := stripCoverageBanner(rewritten)
		rd := ReportDiff{
			Name:       p.name,
			Differs:    oursNorm != theirsNorm,
			OursLines:  strings.Count(oursNorm, "\n") + 1,
			TheirLines: strings.Count(theirsNorm, "\n") + 1,
		}
		if rd.Differs {
			rd.Sample = firstDiffSample(theirsNorm, oursNorm, 8)
		}
		res.Reports = append(res.Reports, rd)
	}
	return res, nil
}

func stripCoverageBanner(s string) string {
	lines := strings.Split(s, "\n")
	out := make([]string, 0, len(lines))
	for _, line := range lines {
		low := strings.ToLower(line)
		if strings.Contains(low, "generated by") ||
			strings.Contains(low, "update-api-coverage.py") ||
			strings.Contains(low, "cbdev docs coverage") ||
			strings.Contains(low, "re-run `make docs`") {
			continue
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

func firstDiffSample(a, b string, n int) string {
	al := strings.Split(a, "\n")
	bl := strings.Split(b, "\n")
	i := 0
	for i < len(al) && i < len(bl) && al[i] == bl[i] {
		i++
	}
	var bld strings.Builder
	fmt.Fprintf(&bld, "first diverge near line %d:\n", i+1)
	for k := 0; k < n; k++ {
		if i+k < len(al) {
			fmt.Fprintf(&bld, "- %s\n", al[i+k])
		}
		if i+k < len(bl) {
			fmt.Fprintf(&bld, "+ %s\n", bl[i+k])
		}
	}
	return bld.String()
}
