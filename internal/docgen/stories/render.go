// RenderIndex builds the release README.md content.
// For release 1.0.0 (no story files), story links point at ../CAP-ID-MAP.md#cap-nnn.
func RenderIndex(release string, every []Story, cfg ReleaseConfig) string {
	prioOrder := []string{"P0", "P1", "P2"}
	stories := filterStatus(every, func(s Story) bool { return s.Status != "Descoped" })
	descoped := filterStatus(every, func(s Story) bool { return s.Status == "Descoped" })
	totalPts := sumPoints(stories)
	byStatus := map[string][]Story{}
	for _, st := range Statuses {
		byStatus[st] = filterStatus(stories, func(s Story) bool { return s.Status == st })
	}
	donePts := sumPoints(byStatus["Implemented"])

	linkFn := storyHref
	if release == "1.0.0" {
		linkFn = mapHref
	}

	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }

	w("# Release " + release + " — Story Index")
	w("")
	w("> Generated by `cbdev docs index` from each story's header table (or `stories.yaml`). " +
		"Don't edit this file by hand: change a story's **Status** (`Not started` → `In progress` → `Implemented`) " +
		"and re-run `make docs`. " +
		"In the priority tables and the phase overview, implemented stories are ~~struck through~~.")
	w("")
	if cfg.Scope != "" {
		w(cfg.Scope)
		w("")
	}
	arch := cfg.Architecture
	if arch == "" {
		arch = "00-architecture.md"
	}
	w("Architecture, domain model, conventions, NFRs and the global Definition of Done: " +
		fmt.Sprintf("[00-architecture.md](%s).", arch))
	w("")
	w("## Snapshot")
	w("")
	w("| Metric | Stories | Story points |")
	w("|---|---|---|")
	w(fmt.Sprintf("| **Total** | **%d** | **%d** |", len(stories), totalPts))
	w(fmt.Sprintf("| ✅ Implemented | %d | %d |", len(byStatus["Implemented"]), donePts))
	w(fmt.Sprintf("| 🚧 In progress | %d | %d |", len(byStatus["In progress"]), sumPoints(byStatus["In progress"])))
	w(fmt.Sprintf("| ⬜ Not started | %d | %d |", len(byStatus["Not started"]), sumPoints(byStatus["Not started"])))
	w(fmt.Sprintf("| Not yet implemented (in progress + not started) | %d | %d |",
		len(stories)-len(byStatus["Implemented"]), totalPts-donePts))
	w(fmt.Sprintf("| **Completion** | %s | %s |", pct(len(byStatus["Implemented"]), len(stories)), pct(donePts, totalPts)))
	if len(descoped) > 0 {
		w(fmt.Sprintf("| 🚫 Descoped (not counted above) | %d | %d |", len(descoped), sumPoints(descoped)))
	}
	w("")

	w("### By priority")
	w("")
	w("| Priority | Meaning | Stories | Points | Implemented (stories / points) |")
	w("|---|---|---|---|---|")
	for _, p := range prioOrder {
		group := filterStatus(stories, func(s Story) bool { return s.Priority == p })
		if len(group) == 0 {
			continue
		}
		done := filterStatus(group, func(s Story) bool { return s.Status == "Implemented" })
		w(fmt.Sprintf("| %s | %s | %d | %d | %d / %d |",
			p, priorityMeaning(release, p), len(group), sumPoints(group), len(done), sumPoints(done)))
	}
	w("")

	epics := orderedEpics(stories)
	w("### By epic")
	w("")
	w("| Epic | Stories | Points | Implemented (stories / points) |")
	w("|---|---|---|---|")
	for _, e := range epics {
		group := filterStatus(stories, func(s Story) bool { return s.Epic == e })
		done := filterStatus(group, func(s Story) bool { return s.Status == "Implemented" })
		w(fmt.Sprintf("| %s | %d | %d | %d / %d |", e, len(group), sumPoints(group), len(done), sumPoints(done)))
	}
	w("")

	w("## Stories by priority")
	w("")
	for _, p := range prioOrder {
		group := filterStatus(stories, func(s Story) bool { return s.Priority == p })
		if len(group) == 0 {
			continue
		}
		w(fmt.Sprintf("### %s — %s (%d stories, %d points)", p, priorityMeaning(release, p), len(group), sumPoints(group)))
		w("")
		w("| # | ID | Story | Epic | Points | Status |")
		w("|---|---|---|---|---|---|")
		for n, s := range group {
			w(priorityRow(n+1, s, linkFn))
		}
		w("")
	}

	w(renderPhases(every, cfg.Phases, linkFn))

	if len(descoped) > 0 {
		w("## Descoped")
		w("")
		w("Kept for reference; not counted in any total. Each story file says why.")
		w("")
		w("| ID | Story | Epic | Points |")
		w("|---|---|---|---|")
		for _, s := range descoped {
			w(fmt.Sprintf("| [%s](%s) | %s | %s | %d |", s.ID, linkFn(s), s.Title, s.Epic, s.Points))
		}
		w("")
	}
	w("## Release checklist")
	w("")
	for _, item := range cfg.Checklist {
		w("- [ ] " + item)
	}
	w("")
	return b.String()
}

// RenderCAPIDMap builds docs/backlog/CAP-ID-MAP.md from 1.0.0 stories.yaml rows.
func RenderCAPIDMap(stories []Story) string {
	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }
	w("# CAP ID map — release 1.0.0")
	w("")
	w("> Generated by `cbdev docs index` from `docs/backlog/release-1.0.0/stories.yaml`. " +
		"Don't edit by hand: update the YAML and re-run `make docs`.")
	w("")
	w("Release 1.0.0 story files are not ported into this repository; this map resolves " +
		"`Depends on CAP-0xx` references from later releases.")
	w("")
	w("| ID | Title | Epic | Priority | Points | Status | Delivered by |")
	w("|---|---|---|---|---|---|---|")
	for _, s := range stories {
		delivered := s.Ref
		if s.Phase != "" {
			if delivered != "" {
				delivered = s.Phase + " · " + delivered
			} else {
				delivered = s.Phase
			}
		}
		if s.Note != "" {
			if delivered != "" {
				delivered += " — " + s.Note
			} else {
				delivered = s.Note
			}
		}
		anchor := strings.ToLower(s.ID)
		w(fmt.Sprintf("| <a id=\"%s\"></a>[%s](#%s) | %s | %s | %s | %d | %s | %s |",
			anchor, s.ID, anchor, s.Title, s.Epic, s.Priority, s.Points, s.Status, delivered))
	}
	w("")
	return b.String()
}

func storyHref(s Story) string {
	if s.File != "" {
		return s.File
	}
	return "../CAP-ID-MAP.md#" + strings.ToLower(s.ID)
}

func mapHref(s Story) string {
	return "../CAP-ID-MAP.md#" + strings.ToLower(s.ID)
}

func priorityRow(n int, s Story, href func(Story) string) string {
	link := fmt.Sprintf("[%s](%s)", s.ID, href(s))
	cells := []string{link, s.Title, s.Epic, fmt.Sprintf("%d", s.Points)}
	var status string
	switch s.Status {
	case "Implemented":
		for i := range cells {
			cells[i] = "~~" + cells[i] + "~~"
		}
		status = "✅ Implemented"
	case "In progress":
		status = "🚧 In progress"
	default:
		status = "⬜ Not started"
	}
	return fmt.Sprintf("| %d | %s |", n, strings.Join(append(cells, status), " | "))
}

func renderPhases(every []Story, phases []Phase, href func(Story) string) string {
	byID := map[string]Story{}
	for _, s := range every {
		byID[s.ID] = s
	}
	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }

	w("## Delivery phases")
	w("")
	w("Stories are delivered in phases; each phase ends with something an operator can run against Capella. " +
		"Within a phase, follow the listed order (each story's **Depends on** column is authoritative).")
	w("")
	w("| Phase | Stories (in order) | Points | Done | Status | Outcome |")
	w("|---|---|---|---|---|---|")
	currentFound := false
	for _, ph := range phases {
		var group []Story
		for _, id := range ph.IDs {
			s := byID[id]
			if s.Status != "Descoped" {
				group = append(group, s)
			}
		}
		done := filterStatus(group, func(s Story) bool { return s.Status == "Implemented" })
		cells := make([]string, 0, len(group))
		for _, s := range group {
			if s.Status == "Implemented" {
				cells = append(cells, "~~"+s.ID+"~~")
			} else {
				cells = append(cells, s.ID)
			}
		}
		var status string
		if len(done) == len(group) {
			status = "✅ Done"
		} else if !currentFound {
			status = "🚧 Current"
			currentFound = true
		} else {
			status = "⬜ Planned"
		}
		w(fmt.Sprintf("| %s | %s | %d | %d/%d (%d pts) | %s | %s |",
			ph.Name, strings.Join(cells, ", "), sumPoints(group),
			len(done), len(group), sumPoints(done), status, ph.Outcome))
	}
	w("")

	w("## Stories by phase")
	w("")
	w("Each phase lists its stories in delivery order.")
	w("")
	currentFound = false
	for _, ph := range phases {
		listed := make([]Story, 0, len(ph.IDs))
		for _, id := range ph.IDs {
			listed = append(listed, byID[id])
		}
		group := filterStatus(listed, func(s Story) bool { return s.Status != "Descoped" })
		done := filterStatus(group, func(s Story) bool { return s.Status == "Implemented" })
		var badge string
		if len(done) == len(group) {
			badge = "✅ Done"
		} else if !currentFound {
			badge = "🚧 Current"
			currentFound = true
		} else {
			badge = "⬜ Planned"
		}
		w(fmt.Sprintf("### %s — %s (%d/%d stories, %d/%d points)",
			ph.Name, badge, len(done), len(group), sumPoints(done), sumPoints(group)))
		w("")
		w(fmt.Sprintf("_%s._", ph.Outcome))
		w("")
		w("| # | ID | Story | Priority | Epic | Points | Depends on | Status |")
		w("|---|---|---|---|---|---|---|---|")
		for n, st := range listed {
			link := fmt.Sprintf("[%s](%s)", st.ID, href(st))
			cells := []string{link, st.Title, st.Priority, st.Epic, fmt.Sprintf("%d", st.Points), st.Depends}
			var status string
			switch st.Status {
			case "Descoped":
				for i := range cells {
					cells[i] = "~~" + cells[i] + "~~"
				}
				status = "🚫 Descoped"
			case "Implemented":
				status = "✅ Implemented"
			case "In progress":
				status = "🚧 In progress"
			default:
				status = "⬜ Not started"
			}
			w(fmt.Sprintf("| %d | %s |", n+1, strings.Join(append(cells, status), " | ")))
		}
		w("")
	}
	return b.String()
}

func filterStatus(in []Story, keep func(Story) bool) []Story {
	var out []Story
	for _, s := range in {
		if keep(s) {
			out = append(out, s)
		}
	}
	return out
}

func sumPoints(in []Story) int {
	n := 0
	for _, s := range in {
		n += s.Points
	}
	return n
}

func pct(a, b int) string {
	if b == 0 {
		return "0%"
	}
	return fmt.Sprintf("%.0f%%", 100*float64(a)/float64(b))
}

func orderedEpics(stories []Story) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range stories {
		if !seen[s.Epic] {
			seen[s.Epic] = true
			out = append(out, s.Epic)
		}
	}
	return out
}
