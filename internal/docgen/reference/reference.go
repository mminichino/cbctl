// Package reference generates docs/capella/reference.md from the Capella YAML schema.
package reference

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/mminichino/cbctl/internal/config/capellafile"
)

const banner = "<!-- Generated by `cbdev docs reference` from internal/config/capellafile/schema.json; do not edit by hand. " +
	"Run `make docs`. -->"

var mutability = map[string]string{
	"updatable":   "updatable",
	"immutable":   "**immutable**",
	"key":         "key",
	"replace":     "re-created",
	"rotate-only": "rotate only",
	"tool":        "cbctl only",
}

var mutabilityHelp = []struct{ key, desc string }{
	{"updatable", "changing the value in the file updates the resource in place"},
	{"immutable", "cannot change after create; remove and recreate"},
	{"key", "identifies the resource; rename is a replace"},
	{"replace", "any change deletes and recreates the resource"},
	{"rotate-only", "password/token fields that rotate rather than update"},
	{"tool", "managed only by cbctl (not sent to Capella)"},
}

// Render builds the reference markdown. When SchemaFields is unavailable it writes a minimal stub.
func Render() (string, error) {
	fields, err := SchemaFields()
	if err != nil || len(fields) == 0 {
		return minimal(), nil
	}
	return renderFrom(fields), nil
}

// SchemaFields returns path → schema node. Prefer capellafile helpers when present.
func SchemaFields() (map[string]map[string]any, error) {
	root, err := capellafile.Schema()
	if err != nil {
		return nil, err
	}
	props, _ := root["properties"].(map[string]any)
	if props == nil {
		return map[string]map[string]any{}, nil
	}
	out := map[string]map[string]any{}
	walk("", props, root, out)
	return out, nil
}

func walk(prefix string, props map[string]any, root map[string]any, out map[string]map[string]any) {
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		node, _ := props[k].(map[string]any)
		if node == nil {
			continue
		}
		node = deref(node, root)
		path := k
		if prefix != "" {
			path = prefix + "." + k
		}
		out[path] = node
		if isSection(node) {
			if nested, ok := node["properties"].(map[string]any); ok {
				walk(path, nested, root, out)
			}
			if items, ok := node["items"].(map[string]any); ok {
				items = deref(items, root)
				if nested, ok := items["properties"].(map[string]any); ok {
					walk(path, nested, root, out)
				}
			}
		}
	}
}

func deref(node, root map[string]any) map[string]any {
	for {
		ref, _ := node["$ref"].(string)
		if ref == "" {
			return node
		}
		ref = strings.TrimPrefix(ref, "#/")
		cur := any(root)
		for _, part := range strings.Split(ref, "/") {
			m, ok := cur.(map[string]any)
			if !ok {
				return node
			}
			cur = m[part]
		}
		next, ok := cur.(map[string]any)
		if !ok {
			return node
		}
		node = next
	}
}

func isSection(node map[string]any) bool {
	if t, _ := node["type"].(string); t == "object" {
		if _, ok := node["properties"]; ok {
			return true
		}
	}
	if t, _ := node["type"].(string); t == "array" {
		items, _ := node["items"].(map[string]any)
		if items != nil {
			if it, _ := items["type"].(string); it == "object" {
				return true
			}
		}
	}
	return false
}

func minimal() string {
	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }
	w("# capella.yaml reference")
	w("")
	w(banner)
	w("")
	w("Every field cbctl reads from `capella.yaml`. Full field tables are generated when the schema walk is available.")
	w("")
	w("**Changes** says what happens when the value is changed in the file and applied:")
	w("")
	for _, m := range mutabilityHelp {
		w(fmt.Sprintf("- **%s**: %s", strings.Trim(mutability[m.key], "*"), m.desc))
	}
	w("")
	w("See `cbctl capella guide config` for offline field help.")
	w("")
	w("## (top level)")
	w("")
	w("| Field | Type | Default | Changes | API | Description |")
	w("|---|---|---|---|---|---|")
	w("| `apiVersion` | string | | key | | Schema version (`cbctl/v1` or `capellactl/v1`) |")
	w("| `organizationId` | string | | immutable | | Capella organization id |")
	w("| `project` / `projects` | object / list | | | | Project and cluster declarations |")
	w("")
	return b.String()
}

func renderFrom(fields map[string]map[string]any) string {
	sections := map[string][]string{"(top level)": {}}
	var sectionOrder []string
	sectionOrder = append(sectionOrder, "(top level)")
	for path, node := range fields {
		if isSection(node) && !strings.Contains(path, ".") {
			if _, ok := sections[path]; !ok {
				sections[path] = nil
				sectionOrder = append(sectionOrder, path)
			}
		}
		_ = node
	}
	paths := make([]string, 0, len(fields))
	for p := range fields {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, path := range paths {
		node := fields[path]
		parent := "(top level)"
		if i := strings.LastIndex(path, "."); i >= 0 {
			parent = path[:i]
			for parent != "(top level)" && sections[parent] == nil && strings.Contains(parent, ".") {
				parent = parent[:strings.LastIndex(parent, ".")]
			}
			if sections[parent] == nil {
				parent = "(top level)"
			}
		}
		if isSection(node) {
			t, _ := node["type"].(string)
			if t == "array" {
				if _, ok := sections[path]; !ok {
					sections[path] = nil
					sectionOrder = append(sectionOrder, path)
				}
				sections[parent] = append(sections[parent], path)
				continue
			}
			continue
		}
		sections[parent] = append(sections[parent], path)
	}

	var b strings.Builder
	w := func(s string) { b.WriteString(s); b.WriteByte('\n') }
	w("# capella.yaml reference")
	w("")
	w(banner)
	w("")
	w("Every field cbctl reads from `capella.yaml`, generated from the schema that `cbctl capella validate` uses. " +
		"The same details are shown offline by `cbctl capella guide config FIELD`.")
	w("")
	w("**Changes** says what happens when the value is changed in the file and applied:")
	w("")
	for _, m := range mutabilityHelp {
		w(fmt.Sprintf("- **%s**: %s", strings.Trim(mutability[m.key], "*"), m.desc))
	}
	w("")
	w("The single-project form (`project:` and `clusters:` at the top level) uses the same fields as `projects[].…`.")
	w("")
	for _, section := range sectionOrder {
		rows := sections[section]
		if len(rows) == 0 {
			continue
		}
		w("## " + section)
		w("")
		if node := fields[section]; node != nil {
			if d, _ := node["description"].(string); d != "" {
				w(cell(d))
				w("")
			}
		}
		w("| Field | Type | Default | Changes | API | Description |")
		w("|---|---|---|---|---|---|")
		for _, path := range rows {
			n := fields[path]
			name := path
			if section != "(top level)" && strings.HasPrefix(path, section+".") {
				name = path[len(section)+1:]
			}
			mut, _ := n["x-mutability"].(string)
			api, _ := n["x-api"].(string)
			desc, _ := n["description"].(string)
			w(fmt.Sprintf("| `%s` | %s | %s | %s | %s | %s |",
				name, cell(typeOf(path, n)), defOf(n), mutability[mut], cell(api), cell(desc)))
		}
		w("")
	}
	return b.String()
}

func cell(text string) string {
	return strings.ReplaceAll(strings.ReplaceAll(text, "|", "\\|"), "\n", " ")
}

func typeOf(path string, node map[string]any) string {
	t, _ := node["type"].(string)
	if t == "" {
		if oneOf, ok := node["oneOf"].([]any); ok {
			var types []string
			seen := map[string]bool{}
			for _, o := range oneOf {
				m, _ := o.(map[string]any)
				if m == nil {
					continue
				}
				if ot, _ := m["type"].(string); ot != "" && !seen[ot] {
					seen[ot] = true
					types = append(types, ot)
				}
			}
			sort.Strings(types)
			t = strings.Join(types, " or ")
		}
	}
	if t == "array" {
		items, _ := node["items"].(map[string]any)
		if items != nil {
			if it, _ := items["type"].(string); it == "object" {
				t = "list of objects"
			} else if it != "" {
				t = "list of " + it
			} else {
				t = "list of values"
			}
		}
	}
	var enum []any
	if e, ok := node["enum"].([]any); ok {
		enum = e
	} else if items, _ := node["items"].(map[string]any); items != nil {
		if e, ok := items["enum"].([]any); ok {
			enum = e
		}
	}
	if len(enum) > 12 {
		parts := make([]string, 0, 4)
		for i := 0; i < 4 && i < len(enum); i++ {
			parts = append(parts, fmt.Sprintf("`%v`", enum[i]))
		}
		t = fmt.Sprintf("%s: %s … (%d values: `cbctl capella guide config %s`)", t, strings.Join(parts, ", "), len(enum), path)
	} else if len(enum) > 0 {
		parts := make([]string, len(enum))
		for i, e := range enum {
			parts[i] = fmt.Sprintf("`%v`", e)
		}
		t = t + ": " + strings.Join(parts, ", ")
	}
	if _, ok := node["minimum"]; ok || node["maximum"] != nil {
		min, max := "…", "…"
		if v, ok := node["minimum"]; ok {
			min = fmt.Sprint(v)
		}
		if v, ok := node["maximum"]; ok {
			max = fmt.Sprint(v)
		}
		t += fmt.Sprintf(" (%s–%s)", min, max)
	}
	if t == "" {
		return "value"
	}
	return t
}

func defOf(node map[string]any) string {
	d, ok := node["default"]
	if !ok {
		return ""
	}
	if b, ok := d.(bool); ok {
		return fmt.Sprintf("`%v`", b)
	}
	return fmt.Sprintf("`%v`", d)
}

// Write generates or checks docs/capella/reference.md relative to repo root.
func Write(repoRoot string, check bool) error {
	text, err := Render()
	if err != nil {
		return err
	}
	out := filepath.Join(repoRoot, "docs", "capella", "reference.md")
	if check {
		cur, err := os.ReadFile(out)
		if err != nil || string(cur) != text {
			return fmt.Errorf("%s is out of date: run 'cbdev docs reference' (or 'make docs') and commit the result", out)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	return os.WriteFile(out, []byte(text), 0o644)
}
